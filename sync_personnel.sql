-- ۱. ساخت جدول
CREATE TABLE IF NOT EXISTS public.personnel (
  id TEXT PRIMARY KEY,
  full_name TEXT NOT NULL,
  national_id TEXT,
  shaba TEXT,
  phone TEXT,
  can_report BOOLEAN DEFAULT false,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- ۲. فعال‌سازی RLS
ALTER TABLE public.personnel ENABLE ROW LEVEL SECURITY;

-- ۳. سیاست خواندن: هر کاربر لاگین‌کرده می‌تواند لیست را ببیند
DROP POLICY IF EXISTS "Authenticated users can view personnel" ON public.personnel;
CREATE POLICY "Authenticated users can view personnel"
ON public.personnel FOR SELECT TO authenticated USING (true);

-- ۴. سیاست تغییر: فقط ادمین‌ها
DROP POLICY IF EXISTS "Admins can modify personnel" ON public.personnel;
CREATE POLICY "Admins can modify personnel"
ON public.personnel FOR ALL TO authenticated
USING ((SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin')
WITH CHECK ((SELECT role FROM public.profiles WHERE id = auth.uid()) = 'admin');

